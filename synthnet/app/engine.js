  function commit(loc, mount, titleStr, opts, tab) {
    var vp = ensureViewport();
    clearNode(vp);
    vp.appendChild(mount);
    try { vp.scrollTop = 0; } catch (e) { /* ignore */ }
    try { window.scrollTo(0, 0); } catch (e2) { /* ignore */ }

    var full = formatLoc(loc);
    if (opts.push !== false) {
      if (tab.url && tab.url !== full) {
        tab.back.push(tab.url);
        if (tab.back.length > MAX_STACK) tab.back.shift();
      }
      tab.fwd.length = 0;
    }
    tab.url = full;
    tab.domain = loc.domain;
    tab.title = titleStr || full;

    setAddress(full);
    document.title = (titleStr ? titleStr + ' - ' : '') + BROWSER_NAME;
    renderTabs();
    updateNavButtons();
    syncHash(full, opts.push === false);
    setProgress(false);
    setStatus('Done');

    /* Record the visit. This is the single choke point every successful
     * navigation passes through with a domain in hand, which makes it the
     * one place "when did you last look at this" can live without threading
     * it through every renderer.
     *
     * The stream ledger goes with it: whatever the page just asked
     * live.stream() for IS what that site watches, so the unread count is
     * derived from what the renderer really did rather than from a table of
     * stream keys kept in sync by hand. See app/alerts.js.
     *
     * Skipped for the app's own pages -- being "behind" on your own settings
     * panel is not a thing. */
    if (SYNTH.alerts && SYNTH.alerts.markVisited && loc.domain &&
        loc.domain !== HOME_DOMAIN && loc.domain !== SEARCH_DOMAIN &&
        loc.domain !== FEEDS_DOMAIN) {
      var feeds = (SYNTH.live && SYNTH.live.ledgerRows) ? SYNTH.live.ledgerRows() : [];
      try { SYNTH.alerts.markVisited(loc.domain, feeds); } catch (e) { /* not fatal */ }
    }

    if (SYNTH.feedsui && SYNTH.feedsui.paintBadge) {
      try { SYNTH.feedsui.paintBadge(); } catch (e) { /* not fatal */ }
    }

    /* Hand the Android app the small part it cannot derive for itself, so
     * the home-screen widget keeps counting with the app closed. A no-op
     * anywhere that is not the app. */
    if (SYNTH.host && SYNTH.host.sync) {
      try { SYNTH.host.sync(); } catch (e) { /* not fatal */ }
    }
  }

  function navigate(url, opts) {
    opts = opts || {};
    var tab = currentTab();
    var loc = resolve(url, tab.domain || HOME_DOMAIN);
    if (!loc.domain) loc.domain = HOME_DOMAIN;
    var full = formatLoc(loc);
    var token = ++navToken;

    setProgress(true);
    setStatus('Opening ' + full + ' …');
    setAddress(full);

    return loadRegistry().then(function () {
      if (token !== navToken) return null;

      if (loc.domain === HOME_DOMAIN) {
        var homeMount = builtinMount('synth-startpage');
        var ht = renderHomePage(homeMount, loc);
        commit(loc, homeMount, ht, opts, tab);
        return null;
      }

      if (loc.domain === FEEDS_DOMAIN) {
        /* Feeds is a page rather than a dropdown so it gets history, the
         * back button and the phone layout for nothing -- and the command
         * bar it hangs off is hidden below 700px, so a dropdown there would
         * be unreachable on the primary target. Drawn by app/feedsui.js. */
        var fm = builtinMount('synth-feedspage');
        var ft = (SYNTH.feedsui && SYNTH.feedsui.render)
          ? SYNTH.feedsui.render(fm, loc)
          : 'Feeds';
        commit(loc, fm, ft, opts, tab);
        return null;
      }

      if (loc.domain === SEARCH_DOMAIN) {
        var q = loc.query && loc.query.q ? loc.query.q : '';
        return search(q).then(function (results) {
          if (token !== navToken) return null;
          var sm = builtinMount('synth-searchpage');
          var st = renderSearchPage(sm, q, results || []);
          commit(loc, sm, st, opts, tab);
          return null;
        }, function () {
          if (token !== navToken) return null;
          var sm2 = builtinMount('synth-searchpage');
          var st2 = renderSearchPage(sm2, q, []);
          commit(loc, sm2, st2, opts, tab);
          return null;
        });
      }

      return getSite(loc.domain).then(function (site) {
        if (token !== navToken) return null;

        if (!site) {
          var errMount = builtinMount('synth-errorpage');
          var et = (!SYNTH.data.registry && !embedded())
            ? renderNoRegistry(errMount, loc)
            : renderNotFound(errMount, loc);
          commit(loc, errMount, et, opts, tab);
          return null;
        }

        var mount = el('div', {
          class: 'synth-page skin-' + (site.skin || 'plain-white'),
          dataset: { domain: loc.domain, type: site.type || '' }
        });

        var pageTitle = site.title || loc.domain;

        /* Clear the arrivals ledger immediately before the renderer runs, so
         * whatever it asks live.stream() for becomes the record of what THIS
         * page is watching. app/tick.js compares against it to say how many
         * things have arrived since. */
        if (SYNTH.live && SYNTH.live.resetLedger) SYNTH.live.resetLedger();
        if (SYNTH.tick && SYNTH.tick.reset) SYNTH.tick.reset();

        var ctx = {
          site: site,
          path: loc.path,
          query: loc.query,
          mount: mount,
          el: SYNTH.el,
          markup: function (text) {
            return (SYNTH.markup && SYNTH.markup.parse)
              ? SYNTH.markup.parse(text)
              : document.createDocumentFragment();
          },
          link: function (href, label, className) { return engineLink(href, label, className); },
          title: function (s) { if (s) pageTitle = String(s); }
        };

        SYNTH.render.render(ctx);
        if (token !== navToken) return null;
        commit(loc, mount, pageTitle, opts, tab);
        return null;
      });
    }).then(null, function (err) {
      if (window.console && console.error) console.error('[synth.engine] navigation failed', err && err.stack ? err.stack : err);
      if (token !== navToken) return null;
      var m = builtinMount('synth-errorpage');
      renderNotFound(m, loc);
      commit(loc, m, 'Cannot find server', opts, tab);
      return null;
    });
  }

