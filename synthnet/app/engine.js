  var tabs = [];
  var activeIndex = 0;
  var tabSeq = 1;
  var navToken = 0;
  var suppressHash = 0;

  function newTabObj() {
    return { id: 't' + (tabSeq++), url: null, domain: HOME_DOMAIN, title: 'New Tab', back: [], fwd: [] };
  }

  function currentTab() {
    if (!tabs.length) { tabs.push(newTabObj()); activeIndex = 0; }
    if (activeIndex < 0 || activeIndex >= tabs.length) activeIndex = tabs.length - 1;
    return tabs[activeIndex];
  }

  function renderTabs() {
    var strip = ensureTabStrip();
    if (!strip) return;
    var newBtn = byId('synth-newtab');
    var keepNew = (newBtn && newBtn.parentNode === strip) ? newBtn : null;
    var kids = [];
    for (var c = 0; c < strip.childNodes.length; c++) kids.push(strip.childNodes[c]);
    for (var d = 0; d < kids.length; d++) {
      if (kids[d] !== keepNew) strip.removeChild(kids[d]);
    }

    tabs.forEach(function (t, i) {
      /* 'synth-tabclose', not 'synth-tab-close': the stylesheet spells it
       * without the second hyphen (theme/aero.css:739), and for a long time
       * this emitted the other spelling, so every tab shipped an unstyled
       * bare "x". */
      var closeBtn = tabs.length > 1 ? el('span', {
        class: 'synth-tabclose',
        title: 'Close Tab',
        onclick: function (ev) { ev.stopPropagation(); ev.preventDefault(); closeTab(i); }
      }, 'x') : null;

      var tabEl = el('div', {
        class: 'synth-tab' + (i === activeIndex ? ' active' : ''),
        title: t.url || 'New Tab',
        dataset: { tabIndex: String(i), tabId: t.id },
        onclick: function () { switchTab(i); },
        onmousedown: function (ev) { if (ev.button === 1) ev.preventDefault(); },
        onauxclick: function (ev) { if (ev.button === 1) { ev.preventDefault(); closeTab(i); } }
      },
        el('span', { class: 'synth-tab-label' }, truncate(t.title || 'New Tab', 26)),
        closeBtn
      );

      if (keepNew) strip.insertBefore(tabEl, keepNew);
      else strip.appendChild(tabEl);
    });
  }

  function newTab(url) {
    tabs.push(newTabObj());
    activeIndex = tabs.length - 1;
    renderTabs();
    return navigate(url || HOME_URL, { push: false });
  }

  function closeTab(i) {
    if (tabs.length <= 1) { setStatus('The last tab cannot be closed.'); return; }
    if (i < 0 || i >= tabs.length) return;
    tabs.splice(i, 1);
    if (activeIndex > i) activeIndex--;
    if (activeIndex >= tabs.length) activeIndex = tabs.length - 1;
    renderTabs();
    var t = currentTab();
    return navigate(t.url || HOME_URL, { push: false });
  }

  function switchTab(i) {
    if (i < 0 || i >= tabs.length || i === activeIndex) return;
    activeIndex = i;
    renderTabs();
    var t = currentTab();
    return navigate(t.url || HOME_URL, { push: false });
  }

  function syncHash(url, replace) {
    var target = '#' + url;
    if (location.hash === target) return;
    suppressHash++;
    try {
      if (replace && window.history && typeof history.replaceState === 'function') {
        history.replaceState(null, '', target);
      } else {
        location.hash = url;
      }
    } catch (e) {
      try { location.hash = url; } catch (e2) { /* ignore */ }
    }
    window.setTimeout(function () { if (suppressHash > 0) suppressHash--; }, 0);
  }

  function back() {
    var t = currentTab();
    if (!t.back.length) return;
    var url = t.back.pop();
    if (t.url) t.fwd.push(t.url);
    navigate(url, { push: false });
  }

  function forward() {
    var t = currentTab();
    if (!t.fwd.length) return;
    var url = t.fwd.pop();
    if (t.url) t.back.push(t.url);
    navigate(url, { push: false });
  }

  function refresh() {
    var t = currentTab();
    if (t.domain) SYNTH.data.forget(t.domain);
    navigate(t.url || HOME_URL, { push: false });
  }

  function stop() {
    navToken++;
    setProgress(false);
    setStatus('Stopped');
  }

