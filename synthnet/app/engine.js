  var siteCache = {};       /* domain -> site|null */
  var registryPromise = null;
  var searchPromise = null;

  function embedded() {
    return (typeof window.SYNTH_EMBEDDED === 'object' && window.SYNTH_EMBEDDED) ? window.SYNTH_EMBEDDED : null;
  }

  function fetchJSON(url) {
    if (typeof window.fetch !== 'function') return Promise.resolve(null);
    try {
      return window.fetch(url).then(function (res) {
        if (!res || !res.ok) return null;
        return res.json().then(function (j) { return j; }, function () { return null; });
      }, function () { return null; });
    } catch (e) {
      return Promise.resolve(null);
    }
  }

  function loadRegistry() {
    if (registryPromise) return registryPromise;
    var emb = embedded();
    if (emb && emb.registry) {
      SYNTH.data.registry = emb.registry;
      registryPromise = Promise.resolve(emb.registry);
      return registryPromise;
    }
    registryPromise = fetchJSON('./net/registry.json').then(function (r) {
      SYNTH.data.registry = r || null;
      return SYNTH.data.registry;
    });
    return registryPromise;
  }

  function registryList() {
    var arr = registryListBuiltIn();
    if (!SYNTH.packs) return arr;

    /* Pack sites join the directory and the search index. Same domain means
     * replace, not duplicate -- two entries for one address would show up as
     * a ghost in the start page listing. */
    var extra = SYNTH.packs.registryRows();
    if (!extra.length) return arr;
    var byDomain = {};
    arr.forEach(function (row) { if (row && row.domain) byDomain[String(row.domain).toLowerCase()] = row; });
    extra.forEach(function (row) { byDomain[String(row.domain).toLowerCase()] = row; });
    var out = [];
    for (var d in byDomain) {
      if (hasOwn(byDomain, d)) out.push(byDomain[d]);
    }
    return out;
  }

  function registryListBuiltIn() {
    var r = SYNTH.data.registry;
    var arr = [];
    var k, v;
    if (!r) return arr;
    if (Array.isArray(r)) arr = r.slice();
    else if (Array.isArray(r.sites)) arr = r.sites.slice();
    else if (r.sites && typeof r.sites === 'object') {
      for (k in r.sites) {
        if (!hasOwn(r.sites, k)) continue;
        v = r.sites[k];
        if (v && typeof v === 'object') {
          if (!v.domain) { v = shallow(v); v.domain = k; }
          arr.push(v);
        }
      }
    } else {
      for (k in r) {
        if (!hasOwn(r, k)) continue;
        v = r[k];
        if (v && typeof v === 'object' && (v.domain || v.type)) {
          if (!v.domain) { v = shallow(v); v.domain = k; }
          arr.push(v);
        }
      }
    }
    var out = [];
    for (var i = 0; i < arr.length; i++) {
      if (arr[i] && arr[i].domain) out.push(arr[i]);
    }
    return out;
  }

  function shallow(o) {
    var c = {};
    for (var k in o) if (hasOwn(o, k)) c[k] = o[k];
    return c;
  }

  function registryEntry(domain) {
    var list = registryList();
    for (var i = 0; i < list.length; i++) {
      if (String(list[i].domain).toLowerCase() === domain) return list[i];
    }
    return null;
  }

  function slugFor(domain, entry) {
    if (entry && entry.slug) return String(entry.slug);
    /* registry.json (generated by tools/build.py) carries the real on-disk
       location as "path"; the folder may have a suffix the domain does not. */
    if (entry && entry.path) {
      var m = String(entry.path).match(/net\/sites\/([^\/]+)\/site\.json$/);
      if (m) return m[1];
    }
    return String(domain).replace(/\./g, '-');
  }

  function getSite(domain) {
    domain = String(domain || '').toLowerCase().trim();
    if (!domain) return Promise.resolve(null);
    if (hasOwn(siteCache, domain)) return Promise.resolve(siteCache[domain]);

    /* Imported packs and sites you authored win over anything built in, so a
     * pack can replace a shipped site by reusing its domain. Checked before
     * the cache is populated, and the cache is dropped on import. */
    if (SYNTH.packs) {
      var over = SYNTH.packs.overlay();
      if (hasOwn(over, domain)) {
        siteCache[domain] = over[domain];
        return Promise.resolve(siteCache[domain]);
      }
    }

    var emb = embedded();
    if (emb && emb.sites && typeof emb.sites === 'object') {
      var s = hasOwn(emb.sites, domain) ? emb.sites[domain] : null;
      siteCache[domain] = s || null;
      return Promise.resolve(siteCache[domain]);
    }

    return loadRegistry().then(function () {
      var slug = slugFor(domain, registryEntry(domain));
      return fetchJSON('./net/sites/' + encodeURIComponent(slug) + '/site.json');
    }).then(function (site) {
      if (site && typeof site === 'object') {
        if (!site.domain) site.domain = domain;
        siteCache[domain] = site;
      } else {
        siteCache[domain] = null;
      }
      return siteCache[domain];
    }, function () {
      siteCache[domain] = null;
      return null;
    });
  }

  SYNTH.data = {
    registry: null,
    getSite: getSite,
    loadRegistry: loadRegistry,
    list: registryList,
    entry: registryEntry,
    forget: function (domain) {
      domain = String(domain || '').toLowerCase();
      if (hasOwn(siteCache, domain)) delete siteCache[domain];
    },

    /* Called by SYNTH.packs after an import, a toggle or a delete. Without
     * this the new sites would not appear until the app was restarted,
     * because both the registry and each loaded site are cached. */
    invalidate: function () {
      siteCache = {};
      searchPromise = null;
    }
  };

