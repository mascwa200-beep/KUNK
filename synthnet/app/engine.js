  function isKnownDomain(d) {
    d = String(d || '').toLowerCase();
    if (d === HOME_DOMAIN || d === SEARCH_DOMAIN || d === FEEDS_DOMAIN) return true;
    return !!registryEntry(d);
  }

  function normalizeTyped(v) {
    v = String(v || '').trim();
    if (!v) return HOME_URL;
    if (/^synth:\/\//i.test(v)) return v;
    if (v.charAt(0) === '#') return v.slice(1);
    if (v.charAt(0) === '/') return v;
    var head = v.split('/')[0].split('?')[0];
    if (head.indexOf('.') !== -1) return 'synth://' + v;
    if (isKnownDomain(head)) return 'synth://' + v;
    return searchUrl(v);
  }

  function addressGo() {
    if (!ui.address) return;
    var v = String(ui.address.value === undefined ? ui.address.textContent : ui.address.value || '').trim();
    if (!v) return;
    navigate(normalizeTyped(v));
  }

  function focusAddress() {
    if (!ui.address) return;
    try { ui.address.focus(); if (ui.address.select) ui.address.select(); } catch (e) { /* ignore */ }
  }

  function hoverUrlOf(a) {
    var raw = null;
    if (a.getAttribute && a.getAttribute('data-synth-href') !== null) raw = a.getAttribute('data-synth-href');
    else if (a.getAttribute) {
      var h = a.getAttribute('href') || '';
      if (/^#?synth:\/\//i.test(h) || h.charAt(0) === '/') raw = h.replace(/^#/, '');
    }
    if (raw === null) return null;
    return formatLoc(resolve(raw, currentTab().domain || HOME_DOMAIN));
  }

  function wireViewport() {
    var vp = ensureViewport();

    vp.addEventListener('click', function (ev) {
      var a = closestTag(ev.target, 'a');
      if (!a) return;
      var raw = a.getAttribute ? a.getAttribute('data-synth-href') : null;
      if (raw === null && a.getAttribute) {
        var h = a.getAttribute('href') || '';
        if (/^#?synth:\/\//i.test(h) || (h.charAt(0) === '/' && h.charAt(1) !== '/')) raw = h.replace(/^#/, '');
      }
      if (raw === null) return;
      ev.preventDefault();
      navigate(raw);
    }, false);

    vp.addEventListener('mouseover', function (ev) {
      var a = closestTag(ev.target, 'a');
      if (!a) return;
      var u = hoverUrlOf(a);
      if (u) setStatus(u);
    }, false);

    vp.addEventListener('mouseout', function (ev) {
      var a = closestTag(ev.target, 'a');
      if (!a) return;
      setStatus('Done');
    }, false);
  }

  function wireChrome() {
    ui.progress = pick('#synth-progress', '.synth-progress');
    ui.address = pick('#synth-address', '.synth-address');
    ui.back = pick('#synth-back', '.synth-back');
    ui.forward = pick('#synth-forward', '.synth-forward');
    /* There are two Home buttons and neither is called '#synth-home'. The
     * command bar has '#synth-cmd-home' and the nav row has '#synth-navhome'
     * -- and the command bar is hidden below 700px (aero.css:1096), which
     * makes the nav-row one *the* Home button on a phone. This used to look
     * for a selector nothing matched, so ui.home was null, no listener was
     * attached, and Home did nothing at all on the primary target. Collect
     * every one that exists rather than picking one. */
    ui.homes = [];
    ['#synth-navhome', '#synth-cmd-home', '#synth-home', '.synth-home'].forEach(function (sel) {
      var node = pick(sel);
      if (node && ui.homes.indexOf(node) === -1) ui.homes.push(node);
    });
    ui.go = pick('#synth-go', '.synth-go');
    ui.newtab = pick('#synth-newtab', '.synth-newtab');
    ui.searchBox = pick('#synth-search', '.synth-search');
    ui.refresh = pick('#synth-refresh', '.synth-refresh');
    ui.stop = pick('#synth-stop', '.synth-stop');

    if (ui.back) ui.back.addEventListener('click', function (e) { e.preventDefault(); back(); }, false);
    if (ui.forward) ui.forward.addEventListener('click', function (e) { e.preventDefault(); forward(); }, false);
    ui.homes.forEach(function (node) {
      node.addEventListener('click', function (e) { e.preventDefault(); navigate(HOME_URL); }, false);
    });

    /* The Feeds button has existed in index.html since the first commit and
     * has never been wired to anything. */
    ui.feeds = pick('#synth-cmd-feeds', '.synth-cmd-feeds');
    if (ui.feeds) {
      ui.feeds.addEventListener('click', function (e) {
        e.preventDefault();
        navigate('synth://' + FEEDS_DOMAIN + '/');
      }, false);
    }
    if (ui.go) ui.go.addEventListener('click', function (e) { e.preventDefault(); addressGo(); }, false);
    if (ui.newtab) ui.newtab.addEventListener('click', function (e) { e.preventDefault(); newTab(); }, false);
    if (ui.refresh) ui.refresh.addEventListener('click', function (e) { e.preventDefault(); refresh(); }, false);
    if (ui.stop) ui.stop.addEventListener('click', function (e) { e.preventDefault(); stop(); }, false);

    if (ui.address) {
      ui.address.addEventListener('keydown', function (e) {
        if (e.key === 'Enter' || e.keyCode === 13) { e.preventDefault(); addressGo(); }
      }, false);
      var form = closestTag(ui.address, 'form');
      if (form) form.addEventListener('submit', function (e) { e.preventDefault(); addressGo(); }, false);
    }

    if (ui.searchBox) {
      var tag = ui.searchBox.tagName ? ui.searchBox.tagName.toUpperCase() : '';
      if (tag === 'INPUT' || tag === 'TEXTAREA') {
        ui.searchBox.addEventListener('keydown', function (e) {
          if (e.key === 'Enter' || e.keyCode === 13) {
            e.preventDefault();
            var v = String(ui.searchBox.value || '').trim();
            navigate(v ? searchUrl(v) : ('synth://' + SEARCH_DOMAIN + '/'));
          }
        }, false);
        var sform = closestTag(ui.searchBox, 'form');
        if (sform) {
          sform.addEventListener('submit', function (e) {
            e.preventDefault();
            var v = String(ui.searchBox.value || '').trim();
            navigate(v ? searchUrl(v) : ('synth://' + SEARCH_DOMAIN + '/'));
          }, false);
        }
        var sgo = pick('#synth-searchgo', '.synth-searchgo');
        if (sgo) {
          sgo.addEventListener('click', function (e) {
            e.preventDefault();
            var v = String(ui.searchBox.value || '').trim();
            navigate(v ? searchUrl(v) : ('synth://' + SEARCH_DOMAIN + '/'));
          }, false);
        }
      } else {
        ui.searchBox.addEventListener('click', function (e) {
          e.preventDefault();
          var box = pick('#synth-searchbox', '.synth-searchbox');
          var v = box && box.value ? String(box.value).trim() : '';
          navigate(v ? searchUrl(v) : ('synth://' + SEARCH_DOMAIN + '/'));
        }, false);
      }
    }

    document.addEventListener('keydown', function (ev) {
      var k = ev.key || '';
      var inField = false;
      var tgt = ev.target;
      if (tgt && tgt.tagName) {
        var tn = tgt.tagName.toUpperCase();
        inField = (tn === 'INPUT' || tn === 'TEXTAREA' || tn === 'SELECT');
      }

      if (ev.altKey && !ev.ctrlKey && !ev.metaKey && (k === 'ArrowLeft' || ev.keyCode === 37)) {
        ev.preventDefault(); back(); return;
      }
      if (ev.altKey && !ev.ctrlKey && !ev.metaKey && (k === 'ArrowRight' || ev.keyCode === 39)) {
        ev.preventDefault(); forward(); return;
      }
      if ((ev.ctrlKey || ev.metaKey) && (k === 't' || k === 'T')) { ev.preventDefault(); newTab(); return; }
      if ((ev.ctrlKey || ev.metaKey) && (k === 'w' || k === 'W')) { ev.preventDefault(); closeTab(activeIndex); return; }
      if ((ev.ctrlKey || ev.metaKey) && (k === 'l' || k === 'L')) { ev.preventDefault(); focusAddress(); return; }
      if (k === 'F5' || ev.keyCode === 116) { ev.preventDefault(); refresh(); return; }
      if (k === 'Escape' || ev.keyCode === 27) {
        stop();
        if (inField && tgt.blur) tgt.blur();
        return;
      }
    }, false);

    window.addEventListener('hashchange', function () {
      if (suppressHash > 0) { suppressHash--; return; }
      var h = String(location.hash || '').replace(/^#/, '');
      if (!h) return;
      var t = currentTab();
      if (t.url === h) return;
      if (t.back.length && t.back[t.back.length - 1] === h) {
        t.back.pop();
        if (t.url) t.fwd.push(t.url);
      } else if (t.fwd.length && t.fwd[t.fwd.length - 1] === h) {
        t.fwd.pop();
        if (t.url) t.back.push(t.url);
      }
      navigate(h, { push: false });
    }, false);
  }

