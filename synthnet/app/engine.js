  function decodeSeg(s) {
    try { return decodeURIComponent(s); } catch (e) { return s; }
  }

  function parseQuery(qs) {
    var out = {};
    if (!qs) return out;
    var parts = String(qs).split('&');
    for (var i = 0; i < parts.length; i++) {
      if (!parts[i]) continue;
      var eq = parts[i].indexOf('=');
      var k = eq === -1 ? parts[i] : parts[i].slice(0, eq);
      var v = eq === -1 ? '' : parts[i].slice(eq + 1);
      k = decodeSeg(k.replace(/\+/g, ' '));
      v = decodeSeg(v.replace(/\+/g, ' '));
      if (k) out[k] = v;
    }
    return out;
  }

  function resolve(href, currentDomain) {
    var raw = String(href === null || href === undefined ? '' : href).trim();
    while (raw.charAt(0) === '#') raw = raw.slice(1);

    var absolute = false;
    if (/^synth:\/\//i.test(raw)) { raw = raw.replace(/^synth:\/\//i, ''); absolute = true; }
    else if (raw.slice(0, 2) === '//') { raw = raw.slice(2); absolute = true; }
    else if (raw.charAt(0) !== '/' && raw !== '') {
      var head = raw.split('/')[0].split('?')[0];
      if (head.indexOf('.') !== -1) absolute = true;
    }

    var domain, pathPart;
    if (absolute) {
      var slash = raw.indexOf('/');
      var qm = raw.indexOf('?');
      var cut;
      if (slash === -1 && qm === -1) cut = raw.length;
      else if (slash === -1) cut = qm;
      else if (qm === -1) cut = slash;
      else cut = Math.min(slash, qm);
      domain = raw.slice(0, cut).toLowerCase();
      pathPart = raw.slice(cut) || '/';
    } else {
      domain = String(currentDomain || '').toLowerCase();
      pathPart = raw.charAt(0) === '/' ? raw : ('/' + raw);
    }

    var hi = pathPart.indexOf('#');
    if (hi !== -1) pathPart = pathPart.slice(0, hi);

    var qs = '';
    var qi = pathPart.indexOf('?');
    if (qi !== -1) { qs = pathPart.slice(qi + 1); pathPart = pathPart.slice(0, qi); }

    var rawSegs = pathPart.split('/');
    var path = [];
    for (var i = 0; i < rawSegs.length; i++) {
      if (rawSegs[i] === '' || rawSegs[i] === '.') continue;
      path.push(decodeSeg(rawSegs[i]));
    }

    return { domain: domain, path: path, query: parseQuery(qs) };
  }

  function formatLoc(loc) {
    var s = 'synth://' + (loc.domain || '');
    var segs = [];
    for (var i = 0; i < (loc.path || []).length; i++) segs.push(encodeURIComponent(loc.path[i]));
    s += '/' + segs.join('/');
    var keys = [];
    for (var k in (loc.query || {})) if (hasOwn(loc.query, k)) keys.push(k);
    if (keys.length) {
      var q = [];
      for (var j = 0; j < keys.length; j++) {
        q.push(encodeURIComponent(keys[j]) + '=' + encodeURIComponent(loc.query[keys[j]]));
      }
      s += '?' + q.join('&');
    }
    return s;
  }

  function searchUrl(q) {
    return 'synth://' + SEARCH_DOMAIN + '/?q=' + encodeURIComponent(String(q || ''));
  }

